window.labFormatLanguage = (text,pick) => {
  let m;
  if ((m=text.match(/^((?:[A-Z]{1,3}\d{1,2}|M2)) · (.+?)　+(.+)$/))) return m[1]+' · '+pick(m[2],m[3]);
  if ((m=text.match(/^([A-Z]{1,3}\d{1,2}) · ([^\u3400-\u9fff]+?)\s+([\u3400-\u9fff].+)$/))) return m[1]+' · '+pick(m[2],m[3]);
  if ((m=text.match(/^(\d+|E\d+) ([^\u3400-\u9fff]+?) · ([\u3400-\u9fff].+)$/))) return m[1]+' '+pick(m[2],m[3]);
  if (text==='Simulations 模擬目錄 ▾') return pick('Simulations ▾','模擬目錄 ▾');
  if (text==='⌂ Home 首頁') return pick('⌂ Home','⌂ 首頁');
  if ((m=text.match(/^Slope difference · 斜率差值( = .+)$/))) return pick('Slope difference','斜率差值')+m[1];
  if ((m=text.match(/^\|割線斜率 − 切線斜率\|(.+)$/))) return pick('|secant slope − tangent slope|','|割線斜率 − 切線斜率|')+m[1];
  if ((m=text.match(/^(-?[\d.]+) (?:units|格)$/))) return pick(m[1]+' units',m[1]+' 單位');
  if (text.startsWith('✓ ')) return '✓ '+labLanguage.label(text.slice(2));
  if ((m=text.match(/^Rectangle (\d+) \/ 長方形 \d+:(.+)$/))) return pick('Rectangle '+m[1],'長方形 '+m[1])+':'+m[2];
  if ((m=text.match(/^(\d+) dots overlap · 靜止時各點重疊$/))) return pick(m[1]+' dots overlap','靜止時 '+m[1]+' 點重疊');
  if ((m=text.match(/^(.+?) (?:numerical )?value(?: \/ 數值)?$/))) return pick(labLanguage.label(m[1])+' value',labLanguage.label(m[1])+'數值');
  if ((m=text.match(/^Adjust (?!調整$)(.+)$/))) return pick(text,'調整'+labLanguage.label(m[1]));
  if ((m=text.match(/^Fixed ([A-Za-z], [A-Za-z]) · .+?固定\. Current (.+)\.$/))) return pick('Fixed '+m[1]+'. Current '+m[2]+'.','固定 '+m[1]+'。目前 '+m[2]+'。');
  if ((m=text.match(/^Ray diagram\. Interface rotation (.+?) degrees clockwise\. Incident from medium (.+?); i (.+?) degrees\. (.+?)\. Drag blue handle.*$/))) return pick(text,'光線圖。交界面順時針轉動 '+m[1]+'°。光由介質 '+m[2]+' 入射，i = '+m[3]+'°。'+m[4].replace('degrees','°')+'。拖曳藍色控制點移動光線，金色控制點旋轉交界面。方向鍵移動光線，Alt 加方向鍵旋轉交界面。');
  if ((m=text.match(/^(Instantaneous speed of P|Estimated instantaneous speed of P|Percentage error) (?:· )?(P 點瞬時速率|百分誤差) ([≈=] .+)$/))){
    const formula=m[3].split('（')[0];
    return pick(m[1],m[2])+' '+pick(formula,formula.replaceAll('estimated speed','估算速率').replaceAll('model speed','模型速率'));
  }
  if (text==='3D 模擬 (Fixed View) - 觀察者視角') return pick('3D simulation (fixed observer view)','3D 模擬（固定觀察者視角）');
  if ((m=text.match(/^([\d.]+) dots · 示意粒子$/))) return pick(m[1]+' representative particles',m[1]+' 粒示意粒子');
  if ((m=text.match(/^Mirror: (.+)$/))) return pick(text,'鏡面：'+m[1]);
  if ((m=text.match(/^Number of readings: (\d+) \(minimum: (\d+)\)$/))) return pick(text,'讀數數目：'+m[1]+'（最少 '+m[2]+' 個）');
};
